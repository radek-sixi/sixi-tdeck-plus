#!/usr/bin/env python3
"""
protocol_drift.py - keep the on-device UI in lock-step with the upstream
MeshCore companion protocol.

The companion protocol is defined (as of companion-v1.18.0) by #define tables
and CLI string handlers in examples/companion_radio/MyMesh.cpp. This tool:

  extract       print the protocol surface for one git ref (markdown or json)
  diff          compare the protocol surface of two refs (e.g. old tag vs new tag)
  check-parity  fail if any CMD_/PUSH_CODE_/CLI key is not mentioned in PARITY.md

Exit codes:
  0  ok / no drift
  1  parity check failed (items missing from PARITY.md) or usage error
  2  diff found additions/changes that need attention

Only the Python standard library is used. Run with -I when pointing it at an
untrusted checkout.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

MYMESH = "examples/companion_radio/MyMesh.cpp"

DEFINE_RE = re.compile(
    r"^\s*#define\s+((?:CMD|RESP_CODE|PUSH_CODE|ERR_CODE)_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)\s*(?://\s*(.*))?$"
)
# companion CLI handled via CMD_RUN_CLI_COMMAND, e.g. memcmp(command, "set wifi.ssid ", 14) / strcmp(command, "get wifi.status")
CLI_RE = re.compile(r'"((?:get|set)\s+[a-z0-9_.]+)')


def read_source(repo: Path, ref: str | None) -> str:
    if ref:
        try:
            return subprocess.run(
                ["git", "-C", str(repo), "show", f"{ref}:{MYMESH}"],
                check=True, capture_output=True, text=True,
            ).stdout
        except subprocess.CalledProcessError as exc:
            sys.exit(f"error: cannot read {MYMESH} at ref '{ref}': {exc.stderr.strip()}")
    path = repo / MYMESH
    if not path.is_file():
        sys.exit(f"error: {path} not found (is --meshcore pointing at a MeshCore checkout?)")
    return path.read_text(encoding="utf-8", errors="replace")


def extract(src: str) -> dict:
    surface: dict[str, dict] = {"CMD": {}, "RESP_CODE": {}, "PUSH_CODE": {}, "ERR_CODE": {}, "CLI": {}}
    for line in src.splitlines():
        m = DEFINE_RE.match(line)
        if m:
            name, value, comment = m.group(1), m.group(2), (m.group(3) or "").strip()
            group = next(g for g in ("RESP_CODE", "PUSH_CODE", "ERR_CODE", "CMD") if name.startswith(g + "_"))
            surface[group][name] = {"value": int(value, 0), "comment": comment}
    for key in sorted(set(k.strip() for k in CLI_RE.findall(src))):
        surface["CLI"][key] = {"value": None, "comment": ""}
    return surface


def to_markdown(surface: dict, title: str) -> str:
    out = [f"# {title}", "",
           "Generated by `scripts/protocol_drift.py extract`. Source of truth: "
           f"`{MYMESH}` in the pinned MeshCore submodule.", ""]
    for group, label in (("CMD", "Commands (app -> radio)"), ("RESP_CODE", "Responses (radio -> app)"),
                         ("PUSH_CODE", "Push notifications (radio -> app, unsolicited)"),
                         ("ERR_CODE", "Error codes"), ("CLI", "Companion CLI keys (via CMD_RUN_CLI_COMMAND)")):
        items = surface[group]
        out += [f"## {label} - {len(items)}", ""]
        if group == "CLI":
            out += [f"- `{k}`" for k in items] + [""]
            continue
        out += ["| Name | Value | Comment |", "|---|---|---|"]
        for name, meta in sorted(items.items(), key=lambda kv: kv[1]["value"]):
            v = meta["value"]
            vs = f"0x{v:02X}" if group == "PUSH_CODE" else str(v)
            out.append(f"| `{name}` | {vs} | {meta['comment']} |")
        out.append("")
    # duplicate value detection (a real hazard: wadamesh reused 62)
    dups = []
    for group in ("CMD", "RESP_CODE", "PUSH_CODE"):
        seen: dict[int, list[str]] = {}
        for name, meta in surface[group].items():
            seen.setdefault(meta["value"], []).append(name)
        dups += [f"{group} value {v}: {', '.join(n)}" for v, n in seen.items() if len(n) > 1]
    out += ["## Duplicate values", ""] + ([f"- {d}" for d in dups] if dups else ["- none"]) + [""]
    return "\n".join(out)


def cmd_extract(args) -> int:
    surface = extract(read_source(Path(args.meshcore), args.ref))
    if args.format == "json":
        print(json.dumps(surface, indent=2, sort_keys=True))
    else:
        print(to_markdown(surface, f"MeshCore companion protocol surface ({args.ref or 'working tree'})"))
    return 0


def cmd_diff(args) -> int:
    repo = Path(args.meshcore)
    a, b = extract(read_source(repo, args.base)), extract(read_source(repo, args.head))
    attention = False
    print(f"# Protocol drift {args.base} -> {args.head}\n")
    for group in a:
        added = sorted(set(b[group]) - set(a[group]))
        removed = sorted(set(a[group]) - set(b[group]))
        changed = sorted(n for n in set(a[group]) & set(b[group]) if a[group][n]["value"] != b[group][n]["value"])
        if not (added or removed or changed):
            continue
        attention = True
        print(f"## {group}")
        for n in added:
            print(f"- ADDED   {n} = {b[group][n]['value']}  {b[group][n]['comment']}")
        for n in removed:
            print(f"- REMOVED {n} (was {a[group][n]['value']})")
        for n in changed:
            print(f"- CHANGED {n}: {a[group][n]['value']} -> {b[group][n]['value']}")
        print()
    if not attention:
        print("No protocol drift.")
        return 0
    print("Action: update docs/PARITY.md and the UI for every ADDED/CHANGED item before bumping the submodule.")
    return 2


def cmd_check_parity(args) -> int:
    surface = extract(read_source(Path(args.meshcore), args.ref))
    parity_path = Path(args.parity)
    if not parity_path.is_file():
        sys.exit(f"error: {parity_path} not found")
    parity = parity_path.read_text(encoding="utf-8")
    missing = []
    for group in ("CMD", "PUSH_CODE", "CLI"):
        for name in surface[group]:
            token = name if group != "CLI" else name.split(None, 1)[1]  # CLI: match the key, e.g. wifi.ssid
            if token not in parity:
                missing.append(f"{group}: {name}")
    if missing:
        print(f"PARITY CHECK FAILED - {len(missing)} protocol items are not mapped in {parity_path}:")
        for m in missing:
            print(f"  - {m}")
        return 1
    total = sum(len(surface[g]) for g in ("CMD", "PUSH_CODE", "CLI"))
    print(f"Parity check OK - all {total} CMD/PUSH/CLI items are mapped in {parity_path}.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    e = sub.add_parser("extract")
    e.add_argument("--meshcore", required=True)
    e.add_argument("--ref")
    e.add_argument("--format", choices=("md", "json"), default="md")
    e.set_defaults(func=cmd_extract)

    d = sub.add_parser("diff")
    d.add_argument("--meshcore", required=True)
    d.add_argument("--base", required=True)
    d.add_argument("--head", required=True)
    d.set_defaults(func=cmd_diff)

    c = sub.add_parser("check-parity")
    c.add_argument("--meshcore", required=True)
    c.add_argument("--parity", required=True)
    c.add_argument("--ref")
    c.set_defaults(func=cmd_check_parity)

    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
